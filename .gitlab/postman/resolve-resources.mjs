// Looks up, via the Postman API, which collections and environment to run in
// POSTMAN_WORKSPACE_ID. Writes a dotenv file (argv[2]) and a child-pipeline
// file with one job per collection (argv[3]).
// Never prints the API key. Fails with a clear message when anything is
// missing or ambiguous.
import { writeFileSync } from "node:fs";

const { POSTMAN_API_KEY, POSTMAN_WORKSPACE_ID, POSTMAN_ENVIRONMENT_ID, POSTMAN_COLLECTION_IDS } = process.env;
const get = async (path) => {
  const r = await fetch(`https://api.getpostman.com${path}`, { headers: { "X-Api-Key": POSTMAN_API_KEY } });
  if (!r.ok) fail(`GET ${path} returned HTTP ${r.status}`);
  return r.json();
};
const fail = (msg) => { console.error(`ERROR: ${msg}`); process.exit(1); };

const { workspace } = await get(`/workspaces/${POSTMAN_WORKSPACE_ID}`);

// Which collections to run: the comma-separated POSTMAN_COLLECTION_IDS if set
// (every one must be in the workspace, otherwise fail), else all of them.
const all = workspace.collections ?? [];
if (!all.length) fail(`workspace ${POSTMAN_WORKSPACE_ID} has no collections`);
const wanted = [...new Set((POSTMAN_COLLECTION_IDS ?? "").split(",").map((x) => x.trim()).filter(Boolean))];
let collections = all;
if (wanted.length) {
  const find = (id) => all.find((c) => c.uid === id || c.id === id);
  const missing = wanted.filter((id) => !find(id));
  if (missing.length) fail(`not in workspace ${POSTMAN_WORKSPACE_ID}: ${missing.join(", ")}. Collections there: ${all.map((c) => `${c.uid} "${c.name}"`).join(", ")}`);
  collections = [...new Set(wanted.map(find))];
}
collections.forEach((c) => console.log(`Collection: ${c.name} (${c.uid})`));

// The environment whose baseUrl points at the Postman mock server, unless
// POSTMAN_ENVIRONMENT_ID names one explicitly.
const envs = [];
for (const e of workspace.environments ?? []) {
  const { environment } = await get(`/environments/${e.uid}`);
  const baseUrl = (environment.values ?? []).find((v) => v.key === "baseUrl")?.value ?? "";
  envs.push({ uid: e.uid, name: e.name, baseUrl });
}
const isMock = (e) => /\.mock\.pstmn\.io/.test(e.baseUrl);
const candidates = POSTMAN_ENVIRONMENT_ID ? envs.filter((e) => e.uid === POSTMAN_ENVIRONMENT_ID || e.uid.endsWith(POSTMAN_ENVIRONMENT_ID)) : envs.filter(isMock);
if (candidates.length !== 1) {
  console.error(`ERROR: expected exactly 1 ${POSTMAN_ENVIRONMENT_ID ? "matching" : "mock"} environment, found ${candidates.length}. Environments in workspace ${POSTMAN_WORKSPACE_ID}:`);
  for (const e of envs) console.error(`  id=${e.uid} name="${e.name}" baseUrl="${e.baseUrl}"`);
  console.error("Set baseUrl on the mock environment in Postman, or set POSTMAN_ENVIRONMENT_ID.");
  process.exit(1);
}
const env = candidates[0];
if (!env.baseUrl) fail(`environment ${env.uid} ("${env.name}") has an empty baseUrl`);
console.log(`Environment: ${env.name} (${env.uid}) baseUrl=${env.baseUrl}`);

// Dotenv for later jobs (IDs only, no secrets).
writeFileSync(process.argv[2], [
  `POSTMAN_ENVIRONMENT_UID=${env.uid}`,
  `POSTMAN_BASE_URL=${env.baseUrl}`,
  `POSTMAN_COLLECTION_UIDS=${collections.map((c) => c.uid).join(",")}`,
  "",
].join("\n"));

// Child pipeline: one job per collection. The job name carries a sanitized slug
// of the collection name so a red job says which collection failed. Values are
// written with JSON.stringify, which is valid YAML, so brackets/spaces are safe.
const slugs = new Set();
const jobs = collections.map((c) => {
  let slug = c.name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") || "collection";
  if (slugs.has(slug)) slug += `-${c.uid.slice(-8)}`;
  slugs.add(slug);
  const q = JSON.stringify;
  return [
    `${q(`postman:run:${slug}`)}:`,
    "  extends: .postman-run-collection",
    "  stage: test",
    "  variables:",
    `    POSTMAN_COLLECTION_UID: ${q(c.uid)}`,
    `    POSTMAN_COLLECTION_NAME: ${q(c.name)}`,
    `    POSTMAN_ENVIRONMENT_UID: ${q(env.uid)}`,
    `    POSTMAN_BASE_URL: ${q(env.baseUrl)}`,
  ].join("\n");
});
writeFileSync(process.argv[3], [
  "# Generated by resolve-resources.mjs: one job per collection.",
  "include:",
  "  - local: .gitlab/postman/cli.gitlab-ci.yml",
  "stages: [test]",
  ...jobs,
  "",
].join("\n\n"));
